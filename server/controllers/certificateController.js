/**
 * Certificate Controller
 * Handles all certificate generation functionality for the TRC-V system
 * Supports PDF and Word document generation for various certificate types
 */

const fs = require('fs').promises;
const path = require('path');
const PizZip = require('pizzip');
const Docxtemplater = require('docxtemplater');
const { fillPDFForm, inspectPDFFields } = require('../utils/pdfFieldMapper');

/**
 * Generate certificate documents (PDF or Word)
 * Supports various certificate types for franchise management
 * POST /api/certificates/generate
 * 
 * @body {string} certificateType - Type of certificate (C.001-APPROVAL, F.008-MTOF-DATE, etc.)
 * @body {object} franchiseData - Data to populate the certificate
 * @body {string} format - Output format ('pdf' or 'docx')
 * @body {string} generatedBy - Name of the person generating the certificate
 * @body {string} generatedDate - Date of generation
 */
exports.generateCertificate = async (req, res, next) => {
    try {
        const { certificateType, franchiseData, format, generatedBy, generatedDate } = req.body;

        // Validation
        if (!certificateType || !franchiseData) {
            return res.status(400).json({ 
                error: 'Certificate type and franchise data are required' 
            });
        }

        if (!format || !['pdf', 'docx'].includes(format)) {
            return res.status(400).json({ 
                error: 'Format must be either pdf or docx' 
            });
        }

        console.log(`[Certificate Generation] Type: ${certificateType}, Format: ${format}`);
        console.log(`[Certificate Generation] Franchise: ${franchiseData.franchiseNumber}`);

        // Validate certificate type
        const validTypes = [
            'C.001-APPROVAL',
            'C.001-CANCELLATION', 
            'F.008-EXISTING',
            'F.008-MTOF-DATE',
            'F.008-MTOF-SUMMARY'
        ];

        if (!validTypes.includes(certificateType)) {
            return res.status(400).json({ 
                error: `Invalid certificate type. Valid types: ${validTypes.join(', ')}` 
            });
        }

        // Log certificate generation for audit trail
        console.log('[Certificate Generation] Generated by:', generatedBy || req.user?.username || 'Unknown');

        // Route to appropriate handler
        if (format === 'pdf') {
            return await generatePDFCertificate(req, res, certificateType, franchiseData, generatedBy, generatedDate);
        } else if (format === 'docx') {
            return await generateWordCertificate(req, res, certificateType, franchiseData, generatedBy, generatedDate);
        }

    } catch (error) {
        console.error('[Certificate Generation] Error:', error);
        return res.status(500).json({ 
            error: error.message || 'Failed to generate certificate' 
        });
    }
};

/**
 * Generate PDF Certificate using fillable PDF forms
 * Uses pdf-lib to fill pre-existing fillable PDF templates
 */
async function generatePDFCertificate(req, res, certificateType, franchiseData, generatedBy, generatedDate) {
    try {
        // Map certificate types to template files
        const templateMap = {
            'C.001-APPROVAL': 'C.001 - CERT APPROVED - FILLABLE.pdf',
            'C.001-CANCELLATION': 'C.001 - CERT CANCELLED - FILLABLE.pdf',
            'F.008-EXISTING': 'F.008 - CERT EXISTING - FILLABLE.pdf'
        };

        const templateFile = templateMap[certificateType];
        if (!templateFile) {
            return res.status(400).json({ 
                error: 'PDF template not available for this certificate type' 
            });
        }

        // Path to template
        const templatePath = path.join(__dirname, '../templates', templateFile);
        
        try {
            await fs.access(templatePath);
        } catch (err) {
            console.error(`[Certificate] Template not found: ${templatePath}`);
            return res.status(500).json({ 
                error: `Certificate template not found: ${templateFile}. Please ensure PDF templates are in the server/templates folder.` 
            });
        }

        // Inspect PDF fields for debugging
        try {
            const fieldInfo = await inspectPDFFields(templatePath);
            console.log(`[Certificate] Template "${templateFile}" has ${fieldInfo.totalFields} form fields`);
            fieldInfo.fields.forEach(f => console.log(`  - ${f.name} (${f.type})`));
        } catch (inspectError) {
            console.warn('[Certificate] Could not inspect PDF fields:', inspectError.message);
        }

        // Prepare complete franchise data for PDF filling with generatedBy
        const resolvedGeneratedBy = generatedBy || franchiseData.generatedBy || 'Administrator';
        const completeFranchiseData = {
            ...franchiseData,
            generatedBy: resolvedGeneratedBy,
            generatedByRole: franchiseData.generatedByRole || req.user?.role || 'Municipal Administrator',
            dateGenerated: generatedDate || new Date().toISOString(),
            municipalityName: franchiseData.municipalityName || 'Municipality of Solano, Nueva Vizcaya'
        };

        console.log(`[Certificate] Generated by: ${resolvedGeneratedBy}`);

        // Fill the PDF form using the smart field mapper
        const pdfBytes = await fillPDFForm(templatePath, completeFranchiseData);

        // Send the PDF with proper headers
        res.setHeader('Content-Type', 'application/pdf');
        res.setHeader('Content-Disposition', `attachment; filename="${certificateType}_${franchiseData.franchiseNumber}_${Date.now()}.pdf"`);
        res.setHeader('Content-Length', pdfBytes.length);
        
        console.log(`[Certificate] PDF generated successfully: ${certificateType}`);
        return res.send(Buffer.from(pdfBytes));

    } catch (error) {
        console.error('[Certificate] PDF generation error:', error);
        throw error;
    }
}

/**
 * Generate Word Document Certificate
 * Uses docxtemplater to fill Word templates with dynamic data
 */
async function generateWordCertificate(req, res, certificateType, franchiseData, generatedBy, generatedDate) {
    try {
        // Map certificate types to template files
        const templateMap = {
            'F.008-MTOF-DATE': 'F.008 - MTOF - DATE.docx',
            'F.008-MTOF-SUMMARY': 'F.008 - MTOF DATE SUMMARY.docx'
        };

        const templateFile = templateMap[certificateType];
        
        if (!templateFile) {
            console.log('[Certificate] No Word template found, generating programmatically');
            return await generateWordProgrammatically(res, certificateType, franchiseData, generatedBy, generatedDate);
        }

        // Use existing template with headers and footers
        const templatePath = path.join(__dirname, '../templates', templateFile);
        
        try {
            await fs.access(templatePath);
            console.log(`[Certificate] Word template found: ${templatePath}`);
        } catch (err) {
            console.error(`[Certificate] Template not found: ${templatePath}`);
            return res.status(500).json({ 
                error: `Word template not found: ${templateFile}. Please ensure the template is in the server/templates folder.` 
            });
        }

        // Load the Word template
        const content = await fs.readFile(templatePath, 'binary');
        const zip = new PizZip(content);
        
        // Configure docxtemplater with proper settings
        const doc = new Docxtemplater(zip, {
            paragraphLoop: true,
            linebreaks: true,
            nullGetter: function(part) {
                // Return empty string for undefined values to avoid errors
                return '';
            }
        });

        // Prepare template data based on certificate type
        const templateData = prepareTemplateData(certificateType, franchiseData, generatedBy, generatedDate);

        console.log('[Certificate] Template data prepared:', {
            type: certificateType,
            hasGrouped: !!franchiseData.grouped,
            hasStats: !!franchiseData.statistics,
            userName: templateData.userName
        });

        // Render the document (replace placeholders)
        doc.render(templateData);

        // Get the filled document as a buffer
        const buffer = doc.getZip().generate({
            type: 'nodebuffer',
            compression: 'DEFLATE'
        });

        // Set proper headers for Word document download
        const filename = `${certificateType}_${franchiseData.franchiseNumber || 'Report'}_${Date.now()}.docx`;
        
        res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
        res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
        res.setHeader('Content-Length', buffer.length);
        
        console.log(`[Certificate] Word document generated successfully: ${filename}`);
        return res.send(buffer);

    } catch (error) {
        console.error('[Certificate] Word generation error:', error.message);
        console.error('[Certificate] Full error:', JSON.stringify(error, Object.getOwnPropertyNames(error), 2));
        
        // Provide more detailed error for template issues
        if (error.properties && error.properties.errors) {
            const detailedErrors = error.properties.errors.map(e => ({
                message: e.message,
                name: e.name,
                properties: e.properties
            }));
            console.error('[Certificate] Template errors:', JSON.stringify(detailedErrors, null, 2));
            
            return res.status(500).json({ 
                error: 'Failed to fill Word template. Template field errors detected.',
                details: detailedErrors
            });
        }
        
        // Return error details for debugging
        return res.status(500).json({
            error: error.message || 'Failed to generate Word document',
            stack: process.env.NODE_ENV !== 'production' ? error.stack : undefined
        });
    }
}

/**
 * Helper function to extract barangay from full address
 */
function extractBarangay(address) {
    if (!address) return 'N/A';
    const parts = address.split(',');
    return parts[0]?.trim() || address;
}

/**
 * Convert number to words (for MTOF SUMMARY)
 */
function numberToWords(num) {
    if (num === 0) return 'zero';
    
    const ones = ['', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
    const tens = ['', '', 'twenty', 'thirty', 'forty', 'fifty', 'sixty', 'seventy', 'eighty', 'ninety'];
    const teens = ['ten', 'eleven', 'twelve', 'thirteen', 'fourteen', 'fifteen', 'sixteen', 'seventeen', 'eighteen', 'nineteen'];
    
    if (num < 10) return ones[num];
    if (num < 20) return teens[num - 10];
    if (num < 100) {
        const ten = Math.floor(num / 10);
        const one = num % 10;
        return tens[ten] + (one ? '-' + ones[one] : '');
    }
    if (num < 1000) {
        const hundred = Math.floor(num / 100);
        const remainder = num % 100;
        return ones[hundred] + ' hundred' + (remainder ? ' and ' + numberToWords(remainder) : '');
    }
    
    // For larger numbers, just return the digit
    return num.toString();
}

/**
 * Prepare template data based on certificate type
 * Includes generatedBy for audit trail on all certificate types
 */
function prepareTemplateData(certificateType, franchiseData, generatedBy, generatedDate) {
    // Use generatedBy from request or franchiseData, with fallback to default
    const resolvedGeneratedBy = generatedBy || franchiseData.generatedBy || 'Administrator';
    const resolvedGeneratedByRole = franchiseData.generatedByRole || 'Municipal Administrator';
    
    const baseData = {
        municipalityName: franchiseData.municipalityName || 'Municipality of Solano, Nueva Vizcaya',
        generatedBy: resolvedGeneratedBy,
        generatedByRole: resolvedGeneratedByRole,
        // Map userName for Word template {userName} tag
        userName: resolvedGeneratedBy,
        dateGenerated: generatedDate 
            ? new Date(generatedDate).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
            : new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' }),
        year: new Date().getFullYear()
    };

    // MTOF DATE - Grouped franchises by application type
    if (certificateType === 'F.008-MTOF-DATE' && franchiseData.grouped) {
        console.log('[Certificate] Processing MTOF DATE with grouped data');
        
        // Prepare grouped franchise arrays matching Word template structure
        // Template loops: {#newApplications}, {#renewalApplications}, {#amendmentApplications}
        // Template fields: {name}, {franchiseNo}, {address}
        const newApplications = (franchiseData.grouped.new || []).map((f) => ({
            name: f.operatorName || 'N/A',
            franchiseNo: f.franchiseNumber || 'N/A',
            address: extractBarangay(f.operatorAddress)
        }));

        const renewalApplications = (franchiseData.grouped.renewal || []).map((f) => ({
            name: f.operatorName || 'N/A',
            franchiseNo: f.franchiseNumber || 'N/A',
            address: extractBarangay(f.operatorAddress)
        }));

        const amendmentApplications = (franchiseData.grouped.amendment || []).map((f) => ({
            name: f.operatorName || 'N/A',
            franchiseNo: f.franchiseNumber || 'N/A',
            address: extractBarangay(f.operatorAddress)
        }));

        console.log(`[Certificate] MTOF DATE data: NEW=${newApplications.length}, RENEWAL=${renewalApplications.length}, AMENDMENT=${amendmentApplications.length}`);

        return {
            ...baseData,
            dateRangeStart: franchiseData.dateRange?.start || 'N/A',
            dateRangeEnd: franchiseData.dateRange?.end || 'N/A',
            newApplications,
            renewalApplications,
            amendmentApplications,
            newCount: newApplications.length,
            renewalCount: renewalApplications.length,
            amendmentCount: amendmentApplications.length
        };
    }

    // MTOF SUMMARY - Statistics summary
    if (certificateType === 'F.008-MTOF-SUMMARY' && franchiseData.statistics) {
        console.log('[Certificate] Processing MTOF SUMMARY with statistics');
        
        // Template expects: {newCountWords}, {renewalCountWords}, {amendmentCountWords}
        return {
            ...baseData,
            newCountWords: numberToWords(franchiseData.statistics.newCount || 0),
            newCount: franchiseData.statistics.newCount || 0,
            renewalCountWords: numberToWords(franchiseData.statistics.renewalCount || 0),
            renewalCount: franchiseData.statistics.renewalCount || 0,
            amendmentCountWords: numberToWords(franchiseData.statistics.amendmentCount || 0),
            amendmentCount: franchiseData.statistics.amendmentCount || 0
        };
    }

    // Standard single franchise certificate
    return {
        ...baseData,
        franchiseNumber: franchiseData.franchiseNumber || 'N/A',
        operatorName: franchiseData.operatorName || 'N/A',
        operatorAddress: franchiseData.operatorAddress || 'N/A',
        plateNumber: franchiseData.mvPlateNo || 'N/A',
        unitModel: franchiseData.unitModel || 'N/A',
        resolutionNumber: franchiseData.resolutionNumber || franchiseData.sbResolutionNumber || 'N/A',
        dateApproved: franchiseData.dateApproved 
            ? new Date(franchiseData.dateApproved).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
            : 'N/A'
    };
}

/**
 * Generate Word document programmatically (fallback)
 */
async function generateWordProgrammatically(res, certificateType, franchiseData, generatedBy, generatedDate) {
    const { Document, Packer, Paragraph, TextRun, AlignmentType } = require('docx');
    
    const children = [
        new Paragraph({
            children: [
                new TextRun({
                    text: 'MUNICIPALITY OF SOLANO, NUEVA VIZCAYA',
                    bold: true,
                    size: 32
                })
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 200 }
        }),
        new Paragraph({
            children: [
                new TextRun({
                    text: certificateType.includes('SUMMARY') 
                        ? 'MOTORIZED TRICYCLE-FOR-HIRE (MTOF) SUMMARY' 
                        : 'Certificate Report',
                    bold: true,
                    size: 28
                })
            ],
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 }
        }),
        new Paragraph({
            children: [
                new TextRun({
                    text: franchiseData.summaryText || `Total Franchises: ${franchiseData.statistics?.total || 0}`,
                    size: 24
                })
            ],
            spacing: { after: 400 }
        }),
        new Paragraph({
            children: [
                new TextRun({
                    text: `Generated by: ${generatedBy || 'Administrator'}`,
                    size: 20
                })
            ],
            spacing: { after: 100 }
        }),
        new Paragraph({
            children: [
                new TextRun({
                    text: `Date: ${generatedDate 
                        ? new Date(generatedDate).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
                        : new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`,
                    size: 20
                })
            ]
        })
    ];
    
    const doc = new Document({
        sections: [{
            properties: {
                page: {
                    margin: {
                        top: 1440,
                        right: 1440,
                        bottom: 1440,
                        left: 1440
                    }
                }
            },
            children: children
        }]
    });

    const buffer = await Packer.toBuffer(doc);
    
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
    res.setHeader('Content-Disposition', `attachment; filename="${certificateType}_${franchiseData.franchiseNumber || 'Summary'}_${Date.now()}.docx"`);
    res.setHeader('Content-Length', buffer.length);
    
    return res.send(buffer);
}

/**
 * Inspect PDF template fields (for debugging)
 * GET /api/certificates/inspect-pdf/:templateName
 * 
 * @param {string} templateName - Template name (approval, cancellation, or existing)
 */
exports.inspectPDFTemplate = async (req, res, next) => {
    try {
        const { templateName } = req.params;
        
        const templateMap = {
            'approval': 'C.001 - CERT APPROVED - FILLABLE.pdf',
            'cancellation': 'C.001 - CERT CANCELLED - FILLABLE.pdf',
            'existing': 'F.008 - CERT EXISTING - FILLABLE.pdf'
        };
        
        const templateFile = templateMap[templateName];
        if (!templateFile) {
            return res.status(400).json({ 
                error: 'Invalid template name. Valid options: approval, cancellation, existing' 
            });
        }
        
        const templatePath = path.join(__dirname, '../templates', templateFile);
        
        try {
            await fs.access(templatePath);
        } catch (err) {
            return res.status(404).json({ 
                error: `Template not found: ${templateFile}` 
            });
        }
        
        const fieldInfo = await inspectPDFFields(templatePath);
        
        res.json({
            template: templateFile,
            path: templatePath,
            ...fieldInfo
        });
    } catch (error) {
        console.error('[PDF Inspector] Error:', error);
        res.status(500).json({ 
            error: error.message || 'Failed to inspect PDF template' 
        });
    }
};

